def name_problem(cat: str, name: str) -> str | None:
    if not any(g in name for g in GARMENT.get(cat, ())):
        return f"'{name}'은(는) {cat} 종류의 옷 이름이 아님 — 흔한 옷 이름(예: 코트, 셔츠, 슬랙스, 로퍼)을 넣어야 함"
    first = name.split()[0]
    if not any(first.startswith(c) for c in COLORS + MATERIALS + SHADES):
        return f"'{name}'은(는) 첫 단어가 색·소재가 아님 — 예: '카멜 울 코트', '블랙 가죽 로퍼', '데님 재킷'"
    return None
